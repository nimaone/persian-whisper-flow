"""قواعد پس‌پردازش متن فارسی — خطاهای سیستماتیک شناخته‌شده‌ی مدل.

قانون بازپیوند می/نمی:
  مدل CTC گاهی پیشوند فعل را به‌صورت توکن مستقل می‌نویسد («می کنم»).
  در فارسی «می» و «نمی» هرگز واژه‌ی مستقل نیستند (به‌جز معنای بسیار نادر
  «می» = شراب)، پس اگر بعدشان واژه‌ی دیگری بیاید، تقسیم اشتباه بوده و
  به همان شکل چسبیده‌ای که مدل خودش درست می‌نویسد («میکنم») برمی‌گردیم.
  سنجش روی ۳۵۰ کلیپ: ۱۵۱ خطا کم شد (WER 34.5% → 31.4%).
"""
from __future__ import annotations

MI_PREFIXES = ("می", "نمی")


def rejoin_prefixes(text: str, prefixes: tuple[str, ...] = MI_PREFIXES) -> str:
    """توکن‌های «می/نمیِ» تنها را به واژه‌ی بعدی می‌چسباند.

    «من می کنم» → «من میکنم» — «می» انتهای جمله دست‌نخورده می‌ماند و
    چسبیدن فقط وقتی انجام می‌شود که واژه‌ی بعدی حروف/رقم داشته باشد
    (به علائم سنجاچ نمی‌چسبد). نیم‌فاصله استفاده نمی‌شود چون خروجی
    درستِ خودِ مدل هم بدون نیم‌فاصله است.
    """
    tokens = text.split()
    out: list[str] = []
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if tok in prefixes and i + 1 < len(tokens) \
                and any(ch.isalnum() for ch in tokens[i + 1]):
            out.append(tok + tokens[i + 1])
            i += 2
        else:
            out.append(tok)
            i += 1
    return " ".join(out)
